// Dynamically load full upstream roles.txt from check-if-email-exists-master if present
try {
  const rolesFilePath = path.join(process.cwd(), "check-if-email-exists-master", "core", "src", "misc", "roles.txt");
  if (fs.existsSync(rolesFilePath)) {
    const content = fs.readFileSync(rolesFilePath, "utf-8");
    content.split(/\r?\n/).forEach((line) => {
      const clean = line.trim().toLowerCase();
      if (clean && !clean.startsWith("#")) {
        ROLE_PREFIXES.add(clean);
      }
    });
  }
} catch {
  // Gracefully fallback to embedded list
}

/**
 * Checks if an email local part is a role-based / generic account.
 */
export function isRoleAccount(localPart: string): boolean {
  if (!localPart) return false;
  const clean = localPart.toLowerCase().trim();
  // Direct match
  if (ROLE_PREFIXES.has(clean)) return true;

  // Check base local part before plus-tag (e.g. support+alerts -> support)
  const baseLocalPart = clean.split("+")[0];
  if (baseLocalPart && ROLE_PREFIXES.has(baseLocalPart)) return true;

  // Split on dots, hyphens, underscores, or pluses (e.g. "sales.team", "it-support", "admin_help", "billing+invoices")
  const parts = clean.split(/[._\-+]/);
  for (const p of parts) {
    if (ROLE_PREFIXES.has(p)) return true;
  }

  return false;
}
